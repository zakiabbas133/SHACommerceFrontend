export const productCategory = (product: Product) =>
  categories.find((category) => category.id === product.categoryId) ||
  categories.find((category) =>
    category.subcategories.some((child) => child.id === product.categoryId),
  );
export const categoryBySlug = (slug: string) => {
  const root = categories.find((category) => category.slug === slug);
  if (root) return root;
  for (const category of categories) {
    const subcategory = category.subcategories.find(
      (child) => child.slug === slug,
    );
    if (subcategory)
      return {
        ...category,
        id: subcategory.id,
        name: subcategory.name,
        slug: subcategory.slug,
        subcategories: [subcategory],
      };
  }
  return undefined;
};
export const productsInCategory = (categoryId: string) => {
  const category = categories.find((item) => item.id === categoryId);
  const ids = new Set([
    categoryId,
    ...(category?.subcategories.map((subcategory) => subcategory.id) || []),
  ]);
  return products.filter((product) => ids.has(product.categoryId));
};
export const formatPrice = (price: number) =>
  new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 2,
  }).format(price);
export const discountPercent = (product: Product) =>
  product.originalPrice
    ? Math.round((1 - product.price / product.originalPrice) * 100)
    : 0;
